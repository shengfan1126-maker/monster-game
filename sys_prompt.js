function recentLog(ctx,n){
  return ctx.filter(e=>!e.ooc&&e.kind!=="ooc").slice(-n).map(e=>e.who==="you"?"玩家："+e.text:(e.kind==="sys"||e.kind==="devour"?"系統：":"敘事：")+gmText(e)).join("\n\n");
}
function buildMessages(tail,ctx){
  const mk=n=>[{role:"system",content:SYS},{role:"user",content:`【目前狀態】\n${JSON.stringify(stateBrief(),null,1)}\n\n【最近發生】\n${recentLog(ctx,n)}\n\n${tail}`}];
  const m=mk(8); m.short=mk(3);   // 被安全過濾擋下時，改送較少的最近故事再試
  return m;
}

